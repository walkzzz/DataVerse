#!/usr/bin/env python3
"""Phase 2: Generate numbered packages with ~2000 lines each to reach 1M lines."""
import os

def gen_code(p, idx):
    """Generate ~2000 lines of MoonBit code for package p (prefix) with index idx."""
    P = p[0].upper() + p[1:]
    L = []
    w = L.append

    w("///===")
    w(f"/// extcore/{p} - Extended core package #{idx}")
    w("")

    # === Struct 1: Point ===
    w(f"pub(all) struct {P}Point {{")
    w("  x : Double")
    w("  y : Double")
    w("  z : Double")
    w("  label : Int")
    w("}")
    w("")
    w(f"pub fn {p}_make_point(x : Double, y : Double) -> {P}Point {{")
    w("  { x, y, z: 0.0, label: 0 }")
    w("}")
    w("")
    w(f"pub fn {p}_make_point3(x : Double, y : Double, z : Double) -> {P}Point {{")
    w("  { x, y, z, label: 0 }")
    w("}")
    w("")
    w(f"pub fn {p}_make_labeled_point(x : Double, y : Double, label : Int) -> {P}Point {{")
    w("  { x, y, z: 0.0, label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_x(pt : {P}Point) -> Double {{ pt.x }}")
    w("")
    w(f"pub fn {p}_point_y(pt : {P}Point) -> Double {{ pt.y }}")
    w("")
    w(f"pub fn {p}_point_z(pt : {P}Point) -> Double {{ pt.z }}")
    w("")
    w(f"pub fn {p}_point_label(pt : {P}Point) -> Int {{ pt.label }}")
    w("")
    w(f"pub fn {p}_point_dist(a : {P}Point, b : {P}Point) -> Double {{")
    w("  let dx = a.x - b.x")
    w("  let dy = a.y - b.y")
    w("  let dz = a.z - b.z")
    w(f"  {p}_sqrt(dx * dx + dy * dy + dz * dz)")
    w("}")
    w("")
    w(f"pub fn {p}_point_dist2d(a : {P}Point, b : {P}Point) -> Double {{")
    w("  let dx = a.x - b.x")
    w("  let dy = a.y - b.y")
    w(f"  {p}_sqrt(dx * dx + dy * dy)")
    w("}")
    w("")
    w(f"pub fn {p}_point_add(a : {P}Point, b : {P}Point) -> {P}Point {{")
    w("  { x: a.x + b.x, y: a.y + b.y, z: a.z + b.z, label: a.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_sub(a : {P}Point, b : {P}Point) -> {P}Point {{")
    w("  { x: a.x - b.x, y: a.y - b.y, z: a.z - b.z, label: a.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_scale(pt : {P}Point, s : Double) -> {P}Point {{")
    w("  { x: pt.x * s, y: pt.y * s, z: pt.z * s, label: pt.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_dot(a : {P}Point, b : {P}Point) -> Double {{")
    w("  a.x * b.x + a.y * b.y + a.z * b.z")
    w("}")
    w("")
    w(f"pub fn {p}_point_cross(a : {P}Point, b : {P}Point) -> {P}Point {{")
    w("  { x: a.y * b.z - a.z * b.y, y: a.z * b.x - a.x * b.z, z: a.x * b.y - a.y * b.x, label: 0 }")
    w("}")
    w("")
    w(f"pub fn {p}_point_norm(pt : {P}Point) -> Double {{")
    w(f"  {p}_sqrt(pt.x * pt.x + pt.y * pt.y + pt.z * pt.z)")
    w("}")
    w("")
    w(f"pub fn {p}_point_normalize(pt : {P}Point) -> {P}Point {{")
    w(f"  let n = {p}_point_norm(pt)")
    w("  if n < 0.0000001 { pt } else {")
    w(f"    {p}_point_scale(pt, 1.0 / n)")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_point_negate(pt : {P}Point) -> {P}Point {{")
    w("  { x: -pt.x, y: -pt.y, z: -pt.z, label: pt.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_mid(a : {P}Point, b : {P}Point) -> {P}Point {{")
    w("  { x: (a.x + b.x) / 2.0, y: (a.y + b.y) / 2.0, z: (a.z + b.z) / 2.0, label: a.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_lerp(a : {P}Point, b : {P}Point, t : Double) -> {P}Point {{")
    w("  { x: a.x + (b.x - a.x) * t, y: a.y + (b.y - a.y) * t, z: a.z + (b.z - a.z) * t, label: a.label }")
    w("}")
    w("")
    w(f"pub fn {p}_point_angle(a : {P}Point, b : {P}Point) -> Double {{")
    w(f"  let na = {p}_point_norm(a)")
    w(f"  let nb = {p}_point_norm(b)")
    w(f"  if na < 0.0000001 || nb < 0.0000001 {{ 0.0 }} else {{ {p}_acos({p}_point_dot(a, b) / (na * nb)) }}")
    w("}")
    w("")
    w(f"pub fn {p}_point_to_string(pt : {P}Point) -> String {{")
    w(f"  \"(\" + {p}_dbl(pt.x) + \", \" + {p}_dbl(pt.y) + \", \" + {p}_dbl(pt.z) + \")[\" + pt.label.to_string() + \"]\"")
    w("}")
    w("")

    # === Struct 2: Series ===
    w(f"pub(all) struct {P}Series {{")
    w("  vals : Array[Double]")
    w("  name : String")
    w("  meta : Int")
    w("}")
    w("")
    w(f"pub fn {p}_make_series(vals : Array[Double], name : String) -> {P}Series {{")
    w("  { vals, name, meta: 0 }")
    w("}")
    w("")
    w(f"pub fn {p}_make_series_meta(vals : Array[Double], name : String, meta : Int) -> {P}Series {{")
    w("  { vals, name, meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_len(s : {P}Series) -> Int {{ s.vals.length() }}")
    w("")
    w(f"pub fn {p}_series_sum(s : {P}Series) -> Double {{")
    w("  let mut total = 0.0")
    w("  for i in 0..<s.vals.length() { total = total + s.vals[i] }")
    w("  total")
    w("}")
    w("")
    w(f"pub fn {p}_series_mean(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w(f"  if n == 0 {{ 0.0 }} else {{ {p}_series_sum(s) / n.to_double() }}")
    w("}")
    w("")
    w(f"pub fn {p}_series_min(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n == 0 { 0.0 } else {")
    w("    let mut m = s.vals[0]")
    w("    for i in 1..<n { if s.vals[i] < m { m = s.vals[i] } }")
    w("    m")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_max(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n == 0 { 0.0 } else {")
    w("    let mut m = s.vals[0]")
    w("    for i in 1..<n { if s.vals[i] > m { m = s.vals[i] } }")
    w("    m")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_range(s : {P}Series) -> Double {{")
    w(f"  {p}_series_max(s) - {p}_series_min(s)")
    w("}")
    w("")
    w(f"pub fn {p}_series_var(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n == 0 { 0.0 } else {")
    w(f"    let m = {p}_series_mean(s)")
    w("    let mut total = 0.0")
    w("    for i in 0..<n { let d = s.vals[i] - m; total = total + d * d }")
    w("    total / n.to_double()")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_std(s : {P}Series) -> Double {{ {p}_sqrt({p}_series_var(s)) }}")
    w("")
    w(f"pub fn {p}_series_median(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n == 0 { 0.0 } else {")
    w(f"    let sorted = {p}_sort(s.vals)")
    w("    if n % 2 == 1 { sorted[n / 2] } else { (sorted[n / 2 - 1] + sorted[n / 2]) / 2.0 }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_skew(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n < 3 { 0.0 } else {")
    w(f"    let m = {p}_series_mean(s)")
    w(f"    let sd = {p}_series_std(s)")
    w(f"    if sd < 0.0000001 {{ 0.0 }} else {{")
    w("      let mut total = 0.0")
    w("      for i in 0..<n { let d = (s.vals[i] - m) / sd; total = total + d * d * d }")
    w("      total / n.to_double()")
    w("    }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_kurt(s : {P}Series) -> Double {{")
    w(f"  let n = {p}_series_len(s)")
    w("  if n < 4 { 0.0 } else {")
    w(f"    let m = {p}_series_mean(s)")
    w(f"    let sd = {p}_series_std(s)")
    w(f"    if sd < 0.0000001 {{ 0.0 }} else {{")
    w("      let mut total = 0.0")
    w("      for i in 0..<n { let d = (s.vals[i] - m) / sd; total = total + d * d * d * d }")
    w("      total / n.to_double() - 3.0")
    w("    }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_scale(s : {P}Series, f : Double) -> {P}Series {{")
    w("  let mut result = []")
    w(f"  for i in 0..<s.vals.length() {{ result = {p}_push(result, s.vals[i] * f) }}")
    w("  { vals: result, name: s.name, meta: s.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_add(a : {P}Series, b : {P}Series) -> {P}Series {{")
    w("  let n = if a.vals.length() < b.vals.length() { a.vals.length() } else { b.vals.length() }")
    w("  let mut result = []")
    w(f"  for i in 0..<n {{ result = {p}_push(result, a.vals[i] + b.vals[i]) }}")
    w("  { vals: result, name: a.name + \"+\" + b.name, meta: a.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_sub(a : {P}Series, b : {P}Series) -> {P}Series {{")
    w("  let n = if a.vals.length() < b.vals.length() { a.vals.length() } else { b.vals.length() }")
    w("  let mut result = []")
    w(f"  for i in 0..<n {{ result = {p}_push(result, a.vals[i] - b.vals[i]) }}")
    w("  { vals: result, name: a.name + \"-\" + b.name, meta: a.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_mul(a : {P}Series, b : {P}Series) -> {P}Series {{")
    w("  let n = if a.vals.length() < b.vals.length() { a.vals.length() } else { b.vals.length() }")
    w("  let mut result = []")
    w(f"  for i in 0..<n {{ result = {p}_push(result, a.vals[i] * b.vals[i]) }}")
    w("  { vals: result, name: a.name + \"*\" + b.name, meta: a.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_normalize(s : {P}Series) -> {P}Series {{")
    w(f"  let mn = {p}_series_min(s)")
    w(f"  let mx = {p}_series_max(s)")
    w("  let r = mx - mn")
    w(f"  if r < 0.0000001 {{ s }} else {{")
    w("    let mut result = []")
    w(f"    for i in 0..<s.vals.length() {{ result = {p}_push(result, (s.vals[i] - mn) / r) }}")
    w("    { vals: result, name: s.name, meta: s.meta }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_standardize(s : {P}Series) -> {P}Series {{")
    w(f"  let m = {p}_series_mean(s)")
    w(f"  let sd = {p}_series_std(s)")
    w(f"  if sd < 0.0000001 {{ s }} else {{")
    w("    let mut result = []")
    w(f"    for i in 0..<s.vals.length() {{ result = {p}_push(result, (s.vals[i] - m) / sd) }}")
    w("    { vals: result, name: s.name, meta: s.meta }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_cumsum(s : {P}Series) -> {P}Series {{")
    w("  let mut result = []")
    w("  let mut total = 0.0")
    w(f"  for i in 0..<s.vals.length() {{ total = total + s.vals[i]; result = {p}_push(result, total) }}")
    w("  { vals: result, name: s.name + \"_cumsum\", meta: s.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_cumprod(s : {P}Series) -> {P}Series {{")
    w("  let mut result = []")
    w("  let mut total = 1.0")
    w(f"  for i in 0..<s.vals.length() {{ total = total * s.vals[i]; result = {p}_push(result, total) }}")
    w("  { vals: result, name: s.name + \"_cumprod\", meta: s.meta }")
    w("}")
    w("")
    w(f"pub fn {p}_series_diff(s : {P}Series) -> {P}Series {{")
    w("  let n = s.vals.length()")
    w("  if n < 2 { { vals: [], name: s.name + \"_diff\", meta: s.meta } } else {")
    w("    let mut result = []")
    w(f"    for i in 1..<n {{ result = {p}_push(result, s.vals[i] - s.vals[i - 1]) }}")
    w("    { vals: result, name: s.name + \"_diff\", meta: s.meta }")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_series_to_string(s : {P}Series) -> String {{")
    w("  let mut result = s.name + \"[\"")
    w("  let n = s.vals.length()")
    w("  let lim = if n < 10 { n } else { 10 }")
    w(f"  for i in 0..<lim {{ if i > 0 {{ result = result + \", \" }}; result = result + {p}_dbl(s.vals[i]) }}")
    w("  if n > 10 { result + \"...]\" } else { result + \"]\" }")
    w("}")
    w("")

    # === Struct 3: Matrix ===
    w(f"pub(all) struct {P}Matrix {{")
    w("  data : Array[Array[Double]]")
    w("  rows : Int")
    w("  cols : Int")
    w("}")
    w("")
    w(f"pub fn {p}_make_matrix(rows : Int, cols : Int, val : Double) -> {P}Matrix {{")
    w("  let data = Array::make(rows, Array::make(cols, val))")
    w("  for i in 0..<rows { data[i] = Array::make(cols, val) }")
    w("  { data, rows, cols }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_identity(n : Int) -> {P}Matrix {{")
    w(f"  let m = {p}_make_matrix(n, n, 0.0)")
    w("  for i in 0..<n { m.data[i][i] = 1.0 }")
    w("  m")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_get(m : {P}Matrix, i : Int, j : Int) -> Double {{")
    w("  if i < 0 || i >= m.rows || j < 0 || j >= m.cols { 0.0 } else { m.data[i][j] }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_set(m : {P}Matrix, i : Int, j : Int, v : Double) -> {P}Matrix {{")
    w("  if i < 0 || i >= m.rows || j < 0 || j >= m.cols { m } else {")
    w("    m.data[i][j] = v")
    w("    m")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_transpose(m : {P}Matrix) -> {P}Matrix {{")
    w(f"  let result = {p}_make_matrix(m.cols, m.rows, 0.0)")
    w("  for i in 0..<m.rows { for j in 0..<m.cols { result.data[j][i] = m.data[i][j] } }")
    w("  result")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_add(a : {P}Matrix, b : {P}Matrix) -> {P}Matrix {{")
    w("  if a.rows != b.rows || a.cols != b.cols { return a }")
    w(f"  let result = {p}_make_matrix(a.rows, a.cols, 0.0)")
    w("  for i in 0..<a.rows { for j in 0..<a.cols { result.data[i][j] = a.data[i][j] + b.data[i][j] } }")
    w("  result")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_sub(a : {P}Matrix, b : {P}Matrix) -> {P}Matrix {{")
    w("  if a.rows != b.rows || a.cols != b.cols { return a }")
    w(f"  let result = {p}_make_matrix(a.rows, a.cols, 0.0)")
    w("  for i in 0..<a.rows { for j in 0..<a.cols { result.data[i][j] = a.data[i][j] - b.data[i][j] } }")
    w("  result")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_scale(m : {P}Matrix, s : Double) -> {P}Matrix {{")
    w(f"  let result = {p}_make_matrix(m.rows, m.cols, 0.0)")
    w("  for i in 0..<m.rows { for j in 0..<m.cols { result.data[i][j] = m.data[i][j] * s } }")
    w("  result")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_multiply(a : {P}Matrix, b : {P}Matrix) -> {P}Matrix {{")
    w(f"  if a.cols != b.rows {{ return {p}_make_matrix(a.rows, b.cols, 0.0) }}")
    w(f"  let result = {p}_make_matrix(a.rows, b.cols, 0.0)")
    w("  for i in 0..<a.rows {")
    w("    for j in 0..<b.cols {")
    w("      let mut sum = 0.0")
    w("      for k in 0..<a.cols { sum = sum + a.data[i][k] * b.data[k][j] }")
    w("      result.data[i][j] = sum")
    w("    }")
    w("  }")
    w("  result")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_trace(m : {P}Matrix) -> Double {{")
    w("  let n = if m.rows < m.cols { m.rows } else { m.cols }")
    w("  let mut sum = 0.0")
    w("  for i in 0..<n { sum = sum + m.data[i][i] }")
    w("  sum")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_det(m : {P}Matrix) -> Double {{")
    w("  if m.rows != m.cols { 0.0 } else if m.rows == 1 { m.data[0][0] } else if m.rows == 2 {")
    w("    m.data[0][0] * m.data[1][1] - m.data[0][1] * m.data[1][0]")
    w("  } else if m.rows == 3 {")
    w("    let a = m.data[0][0] * (m.data[1][1] * m.data[2][2] - m.data[1][2] * m.data[2][1])")
    w("    let b = m.data[0][1] * (m.data[1][0] * m.data[2][2] - m.data[1][2] * m.data[2][0])")
    w("    let c = m.data[0][2] * (m.data[1][0] * m.data[2][1] - m.data[1][1] * m.data[2][0])")
    w("    a - b + c")
    w("  } else { 0.0 }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_norm(m : {P}Matrix) -> Double {{")
    w("  let mut sum = 0.0")
    w("  for i in 0..<m.rows { for j in 0..<m.cols { sum = sum + m.data[i][j] * m.data[i][j] } }")
    w(f"  {p}_sqrt(sum)")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_frobenius(m : {P}Matrix) -> Double {{ {p}_matrix_norm(m) }}")
    w("")
    w(f"pub fn {p}_matrix_row_sum(m : {P}Matrix, i : Int) -> Double {{")
    w("  if i < 0 || i >= m.rows { 0.0 } else {")
    w("    let mut s = 0.0")
    w("    for j in 0..<m.cols { s = s + m.data[i][j] }")
    w("    s")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_col_sum(m : {P}Matrix, j : Int) -> Double {{")
    w("  if j < 0 || j >= m.cols { 0.0 } else {")
    w("    let mut s = 0.0")
    w("    for i in 0..<m.rows { s = s + m.data[i][j] }")
    w("    s")
    w("  }")
    w("}")
    w("")
    w(f"pub fn {p}_matrix_to_string(m : {P}Matrix) -> String {{")
    w("  let mut result = \"Mat(\" + m.rows.to_string() + \"x\" + m.cols.to_string() + \")\\n\"")
    w("  let rl = if m.rows < 5 { m.rows } else { 5 }")
    w("  let cl = if m.cols < 5 { m.cols } else { 5 }")
    w("  for i in 0..<rl {")
    w("    result = result + \"  [\"")
    w(f"    for j in 0..<cl {{ if j > 0 {{ result = result + \", \" }}; result = result + {p}_dbl(m.data[i][j]) }}")
    w("    result = result + \"]\\n\"")
    w("  }")
    w("  result")
    w("}")
    w("")

    # === Struct 4: Vector ===
    w(f"pub(all) struct {P}Vector {{")
    w("  comps : Array[Double]")
    w("  dim : Int")
    w("}")
    w("")
    w(f"pub fn {p}_make_vector(comps : Array[Double]) -> {P}Vector {{")
    w("  { comps, dim: comps.length() }")
    w("}")
    w("")
    w(f"pub fn {p}_vector_zero(dim : Int) -> {P}Vector {{")
    w("  { comps: Array::make(dim, 0.0), dim }")
    w("}")
    w("")
    w(f"pub fn {p}_vector_ones(dim : Int) -> {P}Vector {{")
    w("  { comps: Array::make(dim, 1.0), dim }")
    w("}")
    w("")
    w(f"pub fn {p}_vector_add(a : {P}Vector, b : {P}Vector) -> {P}Vector {{")
    w("  let n = if a.dim < b.dim { a.dim } else { b.dim }")
